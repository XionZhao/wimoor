  `id` BIGINT(19) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `doc_key` VARCHAR(100) NOT NULL COMMENT '文档标识（如：采购单、库存盘点、发货计划等）',
  `title` VARCHAR(200) NOT NULL COMMENT '文档标题',
  `content` TEXT NOT NULL COMMENT '文档内容（Markdown格式）',
  `category` VARCHAR(50) DEFAULT NULL COMMENT '分类（如：erp、amazon、finance、setting等）',
  `keywords` VARCHAR(500) DEFAULT NULL COMMENT '关键词（逗号分隔，用于搜索）',
  `path` VARCHAR(200) DEFAULT NULL COMMENT '页面路径（用于根据URL匹配帮助文档）',
